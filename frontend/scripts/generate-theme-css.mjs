// Generates src/theme/themes.css from src/theme/palettes.json.
// Run after editing palettes: `npm run theme:build`. `--check` fails if the CSS is stale (used in CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { hexToRgb } from './color-utils.mjs';

const root = new URL('../src/theme/', import.meta.url);
const data = JSON.parse(readFileSync(new URL('palettes.json', root), 'utf8'));

const toVar = (token) => `--c-${token.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}`;
const block = (selector, colors, mode) =>
  `${selector} {\n  color-scheme: ${mode};\n${data.tokens
    .map((t) => `  ${toVar(t)}: ${hexToRgb(colors[t]).join(' ')};`)
    .join('\n')}\n}\n`;

const def = data.palettes.find((p) => p.id === data.default.palette);
let css = '/* AUTO-GENERATED by scripts/generate-theme-css.mjs from palettes.json. Do not edit by hand. */\n\n';
css += block(':root', def[data.default.mode], data.default.mode) + '\n';
for (const p of data.palettes) {
  for (const mode of ['dark', 'light']) {
    css += block(`:root[data-palette='${p.id}'][data-mode='${mode}']`, p[mode], mode) + '\n';
  }
}

const target = new URL('themes.css', root);
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current.replace(/\r\n/g, '\n') !== css) {
    console.error('themes.css is out of date. Run `npm run theme:build`.');
    process.exit(1);
  }
  console.log('themes.css is up to date.');
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${data.palettes.length * 2} theme blocks to src/theme/themes.css`);
}
